import copy
import json
from pathlib import Path
import tempfile
import unittest

from scripts.sync_marketplaces import load_catalog, load_tiers, render_outputs, sync


class CatalogFixture:
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        self.catalog = {
            "name": "test-personal", "owner": {"name": "Tester"},
            "plugins": ["plugins/example"],
        }
        plugin = self.root / "plugins/example"
        (plugin / "skills/hello").mkdir(parents=True)
        (plugin / "plugin.json").write_text(json.dumps({
            "name": "example", "version": "0.1.0", "description": "Example skill",
        }))
        (plugin / "skills/hello/SKILL.md").write_text(
            "---\nname: hello\ndescription: Say hello when asked.\n---\nSay hello.\n"
        )
        self.save_catalog()

    def save_catalog(self):
        (self.root / "catalog.json").write_text(json.dumps(self.catalog))


class MarketplaceGenerationTests(CatalogFixture, unittest.TestCase):

    def assert_invalid_without_writes(self):
        with self.assertRaises(ValueError):
            sync(self.root)
        self.assertFalse((self.root / ".claude-plugin").exists())
        self.assertFalse((self.root / ".agents").exists())

    def test_duplicate_plugin_rejected_before_writes(self):
        self.catalog["plugins"].append("plugins/example")
        self.save_catalog()
        self.assert_invalid_without_writes()

    def test_escaping_path_rejected_before_writes(self):
        for path in ("../example", "/tmp/example", "plugins/../../example"):
            with self.subTest(path=path):
                self.catalog["plugins"] = [path]
                self.save_catalog()
                self.assert_invalid_without_writes()

    def test_manifest_identity_must_match_directory(self):
        manifest = self.root / "plugins/example/plugin.json"
        data = json.loads(manifest.read_text())
        data["name"] = "different"
        manifest.write_text(json.dumps(data))
        self.assert_invalid_without_writes()

    def test_missing_plugin_rejected_before_writes(self):
        self.catalog["plugins"] = ["plugins/missing"]
        self.save_catalog()
        self.assert_invalid_without_writes()

    def test_generates_native_sources_pointing_to_same_content(self):
        self.assertTrue(sync(self.root))
        claude = json.loads((self.root / ".claude-plugin/marketplace.json").read_text())
        codex = json.loads((self.root / ".agents/plugins/marketplace.json").read_text())
        self.assertEqual(claude["plugins"][0]["source"], "./plugins/example")
        self.assertEqual(codex["plugins"][0]["source"], {
            "source": "local", "path": "./plugins/example",
        })
        for adapter in (".claude-plugin", ".codex-plugin"):
            manifest = json.loads((self.root / "plugins/example" / adapter / "plugin.json").read_text())
            self.assertEqual(manifest["name"], "example")
            self.assertNotIn("$schema", manifest)

    def test_check_detects_drift_without_mutating_and_sync_repairs(self):
        self.assertFalse(sync(self.root, check=True))
        self.assertFalse((self.root / ".claude-plugin").exists())
        sync(self.root)
        self.assertTrue(sync(self.root, check=True))
        output = self.root / ".agents/plugins/marketplace.json"
        output.write_text("stale\n")
        self.assertFalse(sync(self.root, check=True))
        self.assertEqual(output.read_text(), "stale\n")
        self.assertTrue(sync(self.root))
        self.assertTrue(sync(self.root, check=True))


GENERATED = "<!-- Generated by scripts/sync_marketplaces.py from tiers.json; do not edit. -->"

TIERS = {
    "schema": 1,
    "reference": "skills/hello/reference/hosts.md",
    "routes": {"claude": "definitions", "codex": "spawn"},
    "tiers": {
        "judge": {
            "subagent": False, "role": "plan and rule",
            "hosts": {"claude": {"model": "claude-opus-5-5", "effort": "medium"},
                      "codex": {"model": "gpt-6.1-sol", "effort": "medium"}},
        },
        "execute": {
            "subagent": True, "role": "bulk reading", "description": "Execute tier.",
            "instructions": "Follow the brief.\nStop when stuck.",
            "hosts": {"claude": {"model": "claude-sonnet-5-5"},
                      "codex": {"model": "gpt-6.1-sol", "effort": "low"}},
        },
        "routine": {
            "subagent": True, "role": "mechanical edits", "description": "Routine tier.",
            "instructions": "Follow the brief.",
            "hosts": {"claude": {"model": "claude-haiku-5-5", "effort": "low"},
                      "codex": {"model": "gpt-6-luna"}},
        },
    },
}


class TierGenerationTests(CatalogFixture, unittest.TestCase):
    def setUp(self):
        super().setUp()
        self.plugin = self.root / "plugins/example"
        self.tiers = copy.deepcopy(TIERS)
        self.save_tiers()

    def save_tiers(self):
        (self.plugin / "tiers.json").write_text(json.dumps(self.tiers))

    def hosts_text(self):
        return (self.plugin / "skills/hello/reference/hosts.md").read_text()

    def test_load_tiers_absent_returns_none(self):
        (self.plugin / "tiers.json").unlink()
        self.assertIsNone(load_tiers(self.plugin))

    def test_tiers_generate_claude_agents(self):
        self.assertTrue(sync(self.root))
        agents = self.plugin / "agents"
        self.assertEqual(sorted(p.name for p in agents.iterdir()), ["execute.md", "routine.md"])
        execute = (agents / "execute.md").read_text().splitlines()
        self.assertEqual(execute[:5], [
            "---", "name: execute", 'description: "Execute tier."', "model: claude-sonnet-5-5", "---",
        ])
        self.assertEqual(execute[5:], ["", GENERATED, "", "Follow the brief.", "Stop when stuck."])
        routine = (agents / "routine.md").read_text().splitlines()
        self.assertEqual(routine[:6], [
            "---", "name: routine", 'description: "Routine tier."', "model: claude-haiku-5-5",
            "effort: low", "---",
        ])
        self.assertFalse((agents / "judge.md").exists())
        self.assertTrue(sync(self.root, check=True))

    def test_hosts_reference_lists_every_tier_and_route(self):
        sync(self.root)
        text = self.hosts_text()
        self.assertTrue(text.startswith(GENERATED + "\n"))
        for tier in self.tiers["tiers"].values():
            for host in tier["hosts"].values():
                self.assertIn(host["model"], text)
        for name in ("judge", "execute", "routine"):
            self.assertIn(f"`{name}`", text)
        self.assertIn("`example:execute`", text)
        self.assertIn("Never pass `model` or `effort`", text)
        self.assertIn("CLAUDE_CODE_EFFORT_LEVEL", text)
        self.assertIn("CLAUDE_CODE_SUBAGENT_MODEL_FORCE", text)
        spawn = text.split("### Codex", 1)[1]
        self.assertIn("gpt-6-luna", spawn)
        self.assertIn("`reasoning_effort`", spawn)
        self.assertIn('`fork_turns`: `"none"`', spawn)
        for route, marker in (("same-model", "same model"), ("definitions", "`example-execute`")):
            with self.subTest(route=route):
                self.tiers["routes"]["codex"] = route
                self.save_tiers()
                sync(self.root)
                codex = self.hosts_text().split("### Codex", 1)[1]
                self.assertIn(marker, codex)
                self.assertNotIn("`reasoning_effort`: `\"low\"`", codex)

    def test_hand_edited_agent_fails_check(self):
        sync(self.root)
        agent = self.plugin / "agents/execute.md"
        edited = agent.read_text().replace("Follow the brief.", "Do whatever.")
        agent.write_text(edited)
        self.assertFalse(sync(self.root, check=True))
        self.assertEqual(agent.read_text(), edited)
        self.assertTrue(sync(self.root))
        self.assertIn("Follow the brief.", agent.read_text())

    def test_orphan_agent_is_drift_and_removed_by_sync(self):
        sync(self.root)
        orphan = self.plugin / "agents/judge.md"
        orphan.write_text("---\nname: judge\n---\n")
        self.assertFalse(sync(self.root, check=True))
        self.assertTrue(orphan.exists())
        self.assertTrue(sync(self.root))
        self.assertFalse(orphan.exists())
        self.assertTrue((self.plugin / "agents/execute.md").exists())
        self.assertTrue(sync(self.root, check=True))

    def test_invalid_tiers_rejected_before_writes(self):
        def bad_effort(t): t["tiers"]["execute"]["hosts"]["claude"]["effort"] = "minimal"
        def bad_codex_effort(t): t["tiers"]["execute"]["hosts"]["codex"]["effort"] = "max"
        def missing_model(t): del t["tiers"]["routine"]["hosts"]["codex"]["model"]
        def missing_host(t): del t["tiers"]["routine"]["hosts"]["claude"]
        def escape_up(t): t["reference"] = "../hosts.md"
        def escape_nested(t): t["reference"] = "skills/../../hosts.md"
        def escape_absolute(t): t["reference"] = "/tmp/hosts.md"
        def outside_skills(t): t["reference"] = "agents/hosts.md"
        def bad_schema(t): t["schema"] = 2
        def bad_claude_route(t): t["routes"]["claude"] = "spawn"
        def bad_codex_route(t): t["routes"]["codex"] = "headless"
        def bad_name(t): t["tiers"]["Bad_Name"] = t["tiers"].pop("routine")
        def no_description(t): t["tiers"]["execute"]["description"] = " "
        def no_instructions(t): del t["tiers"]["routine"]["instructions"]
        cases = {
            bad_effort: "effort", bad_codex_effort: "effort", missing_model: "model",
            missing_host: "claude", escape_up: "reference", escape_nested: "reference",
            escape_absolute: "reference", outside_skills: "reference", bad_schema: "schema",
            bad_claude_route: "routes.claude", bad_codex_route: "routes.codex",
            bad_name: "Bad_Name", no_description: "description", no_instructions: "instructions",
        }
        for mutate, field in cases.items():
            with self.subTest(case=mutate.__name__):
                self.tiers = copy.deepcopy(TIERS)
                mutate(self.tiers)
                self.save_tiers()
                with self.assertRaisesRegex(ValueError, field):
                    sync(self.root)
                self.assertFalse((self.root / ".claude-plugin").exists())
                self.assertFalse((self.root / ".agents").exists())
                self.assertFalse((self.plugin / "agents").exists())
                self.assertFalse((self.plugin / "skills/hello/reference").exists())

    def test_plugin_without_tiers_unchanged(self):
        (self.plugin / "tiers.json").unlink()
        before = render_outputs(self.root)
        other = self.root / "plugins/tiered"
        (other / "skills/hello").mkdir(parents=True)
        (other / "plugin.json").write_text(json.dumps({
            "name": "tiered", "version": "0.1.0", "description": "Tiered",
        }))
        (other / "skills/hello/SKILL.md").write_text("---\nname: hello\ndescription: x\n---\n")
        (other / "tiers.json").write_text(json.dumps(TIERS))
        self.catalog["plugins"].append("plugins/tiered")
        self.save_catalog()
        custom = self.plugin / "agents/custom.md"
        custom.parent.mkdir()
        custom.write_text("hand-written\n")
        after = render_outputs(self.root)
        for path, content in before.items():
            if "marketplace.json" not in path.name:
                self.assertEqual(after[path], content)
        self.assertEqual(
            sorted(p.relative_to(self.root).as_posix() for p in after if p.is_relative_to(self.plugin)),
            ["plugins/example/.claude-plugin/plugin.json", "plugins/example/.codex-plugin/plugin.json"],
        )
        self.assertTrue(sync(self.root))
        self.assertTrue(sync(self.root, check=True))
        self.assertEqual(custom.read_text(), "hand-written\n")
        self.assertTrue((other / "agents/execute.md").exists())


if __name__ == "__main__":
    unittest.main()
