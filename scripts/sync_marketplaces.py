#!/usr/bin/env python3
"""Generate host metadata from catalog.json and portable plugin manifests."""

import argparse
import json
from pathlib import Path, PurePosixPath
import re
import sys


ROOT = Path(__file__).resolve().parents[1]
NAME = re.compile(r"[a-z0-9]+(?:-[a-z0-9]+)*\Z")
MODEL = re.compile(r"[A-Za-z0-9][A-Za-z0-9._:/\[\]-]*\Z")
TIERS_FILE = "tiers.json"
GENERATED_NOTE = "<!-- Generated by scripts/sync_marketplaces.py from tiers.json; do not edit. -->"
HOSTS = ("claude", "codex")
EFFORTS = {
    "claude": ("low", "medium", "high", "xhigh", "max"),
    "codex": ("minimal", "low", "medium", "high", "xhigh"),
}
CODEX_ROUTES = ("definitions", "spawn", "same-model")
REFERENCE = re.compile(r"skills/[a-z0-9]+(?:-[a-z0-9]+)*/reference/[a-z0-9]+(?:-[a-z0-9]+)*\.md\Z")


def read_object(path: Path) -> dict:
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as error:
        raise ValueError(f"Cannot read {path}: {error}") from error
    if not isinstance(data, dict):
        raise ValueError(f"Expected a JSON object in {path}")
    return data


def require_name(value: object, label: str) -> None:
    if not isinstance(value, str) or not NAME.fullmatch(value):
        raise ValueError(f"{label} must be a lowercase kebab-case name")


def load_catalog(root: Path) -> tuple[dict, list[tuple[Path, dict]]]:
    root = root.resolve()
    catalog = read_object(root / "catalog.json")
    require_name(catalog.get("name"), "Marketplace name")
    owner = catalog.get("owner")
    if not isinstance(owner, dict) or not isinstance(owner.get("name"), str) or not owner["name"].strip():
        raise ValueError("Catalog owner.name is required")
    paths = catalog.get("plugins")
    if not isinstance(paths, list) or not paths:
        raise ValueError("Catalog plugins must be a nonempty list of relative paths")
    plugins = []
    names = set()
    for value in paths:
        if not isinstance(value, str):
            raise ValueError("Plugin paths must be strings")
        path = Path(value)
        if path.is_absolute() or ".." in path.parts or len(path.parts) != 2 or path.parts[0] != "plugins":
            raise ValueError(f"Plugin path must be plugins/<name>: {value}")
        directory = root / path
        if directory.is_symlink() or not directory.resolve().is_relative_to(root):
            raise ValueError(f"Plugin path escapes the repository or is a symlink: {value}")
        manifest = read_object(directory / "plugin.json")
        name = manifest.get("name")
        require_name(name, f"Plugin name in {value}")
        if name != path.name:
            raise ValueError(f"Plugin name {name} must match directory {path.name}")
        if name in names:
            raise ValueError(f"Duplicate plugin name: {name}")
        names.add(name)
        for key in ("version", "description"):
            if not isinstance(manifest.get(key), str) or not manifest[key].strip():
                raise ValueError(f"Plugin {name} requires a nonempty {key}")
        if not any((directory / "skills").glob("*/SKILL.md")):
            raise ValueError(f"Plugin {name} must include at least one skills/<name>/SKILL.md")
        plugins.append((path, manifest))
    return catalog, plugins


def _nonempty_text(value: object, label: str) -> str:
    if isinstance(value, list) and value and all(isinstance(line, str) for line in value):
        value = "\n".join(value)
    if not isinstance(value, str) or not value.strip():
        raise ValueError(f"{label} must be nonempty text")
    return value.strip()


def load_tiers(plugin_dir: Path) -> dict | None:
    """Read and validate plugin_dir/tiers.json; None when the plugin has none."""
    path = plugin_dir / TIERS_FILE
    if not path.exists():
        return None
    data = read_object(path)
    where = str(path)
    if data.get("schema") != 1:
        raise ValueError(f"{where}: schema must be 1")
    reference = data.get("reference")
    if (
        not isinstance(reference, str) or not REFERENCE.fullmatch(reference)
        or not (plugin_dir / reference).resolve().is_relative_to((plugin_dir / "skills").resolve())
    ):
        raise ValueError(
            f"{where}: reference must be skills/<skill>/reference/<name>.md inside the plugin, got {reference!r}"
        )
    routes = data.get("routes")
    if not isinstance(routes, dict) or set(routes) != set(HOSTS):
        raise ValueError(f"{where}: routes must have exactly the keys {', '.join(HOSTS)}")
    if routes["claude"] != "definitions":
        raise ValueError(f"{where}: routes.claude must be \"definitions\", got {routes['claude']!r}")
    if routes["codex"] not in CODEX_ROUTES:
        raise ValueError(f"{where}: routes.codex must be one of {', '.join(CODEX_ROUTES)}, got {routes['codex']!r}")
    tiers = data.get("tiers")
    if not isinstance(tiers, dict) or not tiers:
        raise ValueError(f"{where}: tiers must be a nonempty object")
    for name, tier in tiers.items():
        label = f"{where}: tiers.{name}"
        require_name(name, f"{where}: tier name {name!r}")
        if not isinstance(tier, dict):
            raise ValueError(f"{label} must be an object")
        if not isinstance(tier.get("subagent"), bool):
            raise ValueError(f"{label}.subagent must be true or false")
        tier["role"] = _nonempty_text(tier.get("role"), f"{label}.role")
        if tier["subagent"]:
            tier["description"] = _nonempty_text(tier.get("description"), f"{label}.description")
            tier["instructions"] = _nonempty_text(tier.get("instructions"), f"{label}.instructions")
            if "````" in tier["instructions"]:
                raise ValueError(f"{label}.instructions must not contain a ```` fence")
        hosts = tier.get("hosts")
        if not isinstance(hosts, dict):
            raise ValueError(f"{label}.hosts must be an object")
        for host in HOSTS:
            entry = hosts.get(host)
            if not isinstance(entry, dict):
                raise ValueError(f"{label}.hosts.{host} is required")
            unknown = set(entry) - {"model", "effort"}
            if unknown:
                raise ValueError(f"{label}.hosts.{host} has unknown fields: {', '.join(sorted(unknown))}")
            if not isinstance(entry.get("model"), str) or not MODEL.fullmatch(entry["model"]):
                raise ValueError(f"{label}.hosts.{host}.model must be a nonempty model id")
            if "effort" in entry and entry["effort"] not in EFFORTS[host]:
                raise ValueError(
                    f"{label}.hosts.{host}.effort must be one of {'|'.join(EFFORTS[host])}, got {entry['effort']!r}"
                )
        extra = set(hosts) - set(HOSTS)
        if extra:
            raise ValueError(f"{label}.hosts has unknown hosts: {', '.join(sorted(extra))}")
    return data


def _setting(entry: dict) -> str:
    effort = f"effort `{entry['effort']}`" if "effort" in entry else "default effort"
    return f"`{entry['model']}`, {effort}"


def _codex_start(plugin: str, route: str, subagents: list[tuple[str, dict]]) -> list[str]:
    lines = ["The delegation skill is your explicit instruction to spawn these subagents.", ""]
    if route == "spawn":
        lines += [
            "Codex plugins can't ship agent definitions, so spawn the default subagent with the",
            "tier's model and effort. Call `spawn_agent` with:",
            "",
            "- `task_name`: lowercase letters, digits and underscores only (Codex rejects anything else), such as the id lowercased with `-` and `.` as `_`",
            '- `fork_turns`: `"none"`, always. A forked child inherits your context, which defeats delegation.',
            "- `model` and `reasoning_effort`: the tier's values below, given explicitly",
            "- `message`: this tier's instructions (under \"Tier instructions\" below) at the top of `message`,",
            "  followed by the loader line",
            "",
            "Per tier:",
            "",
        ]
        for name, tier in subagents:
            entry = tier["hosts"]["codex"]
            if "effort" in entry:
                effort = f'`reasoning_effort`: `"{entry["effort"]}"`'
            else:
                effort = "omit `reasoning_effort` (the model's default)"
            lines.append(f'- `{name}`: `model`: `"{entry["model"]}"`, {effort}')
        lines += [
            "",
            "If `spawn_agent` rejects `model` or `reasoning_effort`, spawn without them, keep the",
            "tier's instructions at the top of `message`, and name the tier in the brief: same",
            "model, default effort.",
        ]
    elif route == "same-model":
        lines += [
            "Spawn a subagent on the same model as you: `spawn_agent` with `fork_turns`: `\"none\"`,",
            "without `model` or `reasoning_effort`. Put the tier's instructions (under \"Tier",
            "instructions\" below) at the top of `message`, followed by the loader line. Put the",
            "tier name in the brief; effort stays the default.",
        ]
    else:
        lines += ["Start the tier's agent by name, with the loader line as its task:", ""]
        lines += [f"- `{name}`: `{plugin}-{name}`" for name, _ in subagents]
    return lines


def _claude_alias(model_id: str) -> str:
    """Agent tool `model` alias for a Claude model id: the word after `claude-`."""
    match = re.match(r"claude-(opus|sonnet|haiku|fable)-", model_id)
    if not match:
        raise ValueError(f"cannot derive a Claude model alias from {model_id!r}")
    return match.group(1)


def render_tiers(plugin_path: Path, tiers: dict) -> dict[Path, str]:
    """Render tier agents and the host table; keys are repo-relative paths."""
    plugin = plugin_path.name
    outputs = {}
    subagents = [(name, tier) for name, tier in tiers["tiers"].items() if tier["subagent"]]
    for name, tier in subagents:
        claude = tier["hosts"]["claude"]
        front = ["---", f"name: {name}", f"description: {json.dumps(tier['description'], ensure_ascii=False)}", f"model: {claude['model']}"]
        if "effort" in claude:
            front.append(f"effort: {claude['effort']}")
        front.append("---")
        outputs[plugin_path / "agents" / f"{name}.md"] = "\n".join(
            [*front, "", GENERATED_NOTE, "", tier["instructions"]]
        ) + "\n"
    lines = [
        GENERATED_NOTE, "", "# Delegation tiers on each host", "",
        "| Tier | Role | Claude Code | Codex |", "|---|---|---|---|",
    ]
    for name, tier in tiers["tiers"].items():
        hosts = tier["hosts"]
        lines.append(f"| `{name}` | {tier['role']} | {_setting(hosts['claude'])} | {_setting(hosts['codex'])} |")
    main = [f"`{name}`" for name, tier in tiers["tiers"].items() if not tier["subagent"]]
    if main:
        lines += [
            "", f"{', '.join(main)} is the main session: no definition, never spawned. Its row is the",
            "expected setting for the session, which the skill can't set.",
        ]
    lines += [
        "", "## Starting a tier", "",
        "Start a tier only after `check.py open`. Its task is this loader line, not the brief's",
        "text; `brief` prints the brief recorded at `open` and refuses if the file has changed:",
        "",
        "    Run `python3 <absolute skill-dir>/scripts/check.py --root <absolute worktree root> brief --delegation <id>` and follow the brief it prints exactly.",
        "",
        "Tools don't expand shell syntax, so never pass `$(cat ...)` or a bare path as the task.",
        "", "### Claude Code", "",
        "Use the Agent tool with `subagent_type` set to the tier's agent:", "",
    ]
    lines += [f"- `{name}`: `{plugin}:{name}`" for name, _ in subagents]
    lines += [
        "",
        "Never pass `model` or `effort`: the generated definition sets them, and a per-call",
        "value overrides it. The environment overrides definitions too: `CLAUDE_CODE_EFFORT_LEVEL`",
        "sets every agent's effort, and `CLAUDE_CODE_SUBAGENT_MODEL_FORCE` with",
        "`CLAUDE_CODE_SUBAGENT_MODEL` forces every subagent's model. If either is set, the table",
        "doesn't hold; say so once.",
        "",
        f"If the `{plugin}:<tier>` agents aren't available, start a general-purpose subagent with the",
        "tier's instructions (under \"Tier instructions\" below) at the top of the prompt, followed by",
        "the loader line, and pass `model` as the tier's alias below (this fallback is the only",
        "case that passes `model`). Never pass `effort`; it stays at the default. Name the tier in",
        "the brief.",
        "",
        *[f"- `{name}`: `model` = `{_claude_alias(tier['hosts']['claude']['model'])}`" for name, tier in subagents],
        "", f"### Codex (route: {tiers['routes']['codex']})", "",
        *_codex_start(plugin, tiers["routes"]["codex"], subagents),
        "", "## Tier instructions", "",
        "Each tier's generated instructions, verbatim. A Claude Code tier agent already has them;",
        "any other way of starting a tier puts them at the top of the task, before the brief.",
    ]
    for name, tier in subagents:
        lines += ["", f"### `{name}`", "", "````text", tier["instructions"], "````"]
    outputs[plugin_path / tiers["reference"]] = "\n".join(lines) + "\n"
    return outputs


def orphan_outputs(root: Path, outputs: dict[Path, str]) -> list[Path]:
    """Agent files in plugins with tiers.json that the generator doesn't produce."""
    _, plugins = load_catalog(root)
    orphans = []
    for path, _ in plugins:
        directory = root / path
        if (directory / TIERS_FILE).exists():
            orphans += [file for file in sorted((directory / "agents").glob("*.md")) if file not in outputs]
    return orphans


def render_outputs(root: Path) -> dict[Path, str]:
    catalog, plugins = load_catalog(root)
    claude = {key: catalog[key] for key in ("name", "owner", "description") if key in catalog}
    codex = {"name": catalog["name"]}
    claude["plugins"] = []
    codex["plugins"] = []
    outputs = {}
    texts = {}
    for path, portable in plugins:
        tiers = load_tiers(root.resolve() / path)
        if tiers is not None:
            if (root / path / "agents").is_symlink():
                raise ValueError(f"{path / 'agents'} must be a directory, not a symlink")
            texts.update(render_tiers(path, tiers))
        identity = {key: portable[key] for key in ("name", "version", "description", "author", "keywords") if key in portable}
        source = "./" + path.as_posix()
        claude["plugins"].append({**identity, "source": source})
        codex["plugins"].append({
            "name": portable["name"],
            "source": {"source": "local", "path": source},
            "policy": {"installation": "AVAILABLE", "authentication": "ON_INSTALL"},
            "category": "Productivity",
        })
        outputs[path / ".claude-plugin/plugin.json"] = identity
        outputs[path / ".codex-plugin/plugin.json"] = {**identity, "skills": "./skills/"}
    outputs[Path(".claude-plugin/marketplace.json")] = claude
    outputs[Path(".agents/plugins/marketplace.json")] = codex
    rendered = {root / path: json.dumps(data, indent=2, ensure_ascii=False) + "\n" for path, data in outputs.items()}
    rendered.update({root / path: content for path, content in texts.items()})
    return rendered


def sync(root: Path, check: bool = False) -> bool:
    outputs = render_outputs(root)  # Validate every input before touching outputs.
    orphans = orphan_outputs(root, outputs)
    matches = not orphans
    if not check:
        for path in orphans:
            path.unlink()
    for path, content in outputs.items():
        if path.exists() and path.read_text(encoding="utf-8") == content:
            continue
        matches = False
        if not check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
    return matches if check else True


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=ROOT)
    parser.add_argument("--check", action="store_true", help="Fail on drift without writing files")
    args = parser.parse_args()
    try:
        if not sync(args.root, args.check):
            print("Generated metadata differs; run scripts/sync_marketplaces.py", file=sys.stderr)
            return 1
    except (ValueError, OSError) as error:
        print(error, file=sys.stderr)
        return 1
    print("Generated metadata is current." if args.check else "Generated host metadata.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
